function generateSmartContent(fullPath, fileName) {
    const lowerName = fileName.toLowerCase();
    const parts = fullPath.split('/');
    const folderName = parts.length > 1 ? parts[parts.length - 2] : 'project';

    // 1. Cấu hình tệp đặc biệt
    if (lowerName === 'package.json') {
        return JSON.stringify({
            name: folderName,
            version: "1.0.0",
            description: "Generated by Hendy Edge Studio",
            main: "index.js",
            scripts: { "start": "node index.js", "dev": "node --watch index.js" },
            dependencies: {}
        }, null, 2);
    }
    if (lowerName === 'dockerfile') {
        return `FROM node:18-alpine\nWORKDIR /app\nCOPY package*.json ./\nRUN npm install\nCOPY . .\nEXPOSE 3000\nCMD ["npm", "start"]`;
    }
    if (lowerName === 'docker-compose.yml' || lowerName === 'docker-compose.yaml') {
        return `version: '3.8'\nservices:\n  ${folderName}-app:\n    build: .\n    ports:\n      - "3000:3000"\n    restart: always`;
    }
    if (lowerName === '.env' || lowerName === '.env.example') {
        return `# Biến môi trường cho dự án ${folderName}\nPORT=3000\nNODE_ENV=development\nDATABASE_URL=postgres://user:password@localhost:5432/mydb`;
    }

    // 2. Cấu hình tệp React / JSX / TSX
    if (lowerName.endsWith('.tsx') || lowerName.endsWith('.jsx')) {
        const compName = fileName.split('.')[0];
        const capitalized = compName.charAt(0).toUpperCase() + compName.slice(1);
        return `import React from 'react';\n\nexport default function ${capitalized}() {\n  return (\n    <div className="p-6 max-w-sm mx-auto bg-white rounded-xl shadow-md flex items-center space-x-4">\n      <div>\n        <div className="text-xl font-medium text-black">${capitalized} Component</div>\n        <p className="text-slate-500">Tự động sinh bởi Hendy Cloudflare Edge</p>\n      </div>\n    </div>\n  );\n}`;
    }

    // 3. Cấu hình mã nguồn cho các ngôn ngữ lập trình & Cơ sở dữ liệu
    if (['.js', '.ts', '.py', '.kt', '.go', '.java', '.sql', '.rs'].some(ext => lowerName.endsWith(ext))) {
        let comment = '//';
        if (lowerName.endsWith('.py') || lowerName.endsWith('.sql')) {
            comment = '--';
        } else if (lowerName.endsWith('.rs')) {
            comment = '//';
        }
        
        return `${comment} ==========================================\n${comment} File: ${fileName}\n${comment} Module: ${folderName}\n${comment} Tự động sinh bởi Hendy Cloudflare Edge\n${comment} ==========================================\n\n`;
    }

    return ``; 
}
